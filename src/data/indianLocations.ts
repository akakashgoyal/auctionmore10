/**
 * Returns list of cities under a specific state name (case-insensitive)
 */
export function getCitiesForState(stateName: string): string[] {
  if (!stateName || stateName === 'All' || stateName === 'all') {
    return [];
  }
  const cleanState = stateName.trim().toLowerCase();
  const match = INDIAN_STATES_CITIES.find(
    (s) => s.name.toLowerCase() === cleanState || s.code.toLowerCase() === cleanState
  );
  return match ? [...match.cities].sort() : [];
}

/**
 * Reverse lookup: Find the state name that a given city belongs to
 */
export function findStateForCity(cityName: string): string | null {
  if (!cityName || !cityName.trim()) return null;
  const cleanCity = cityName.trim().toLowerCase();

  for (const s of INDIAN_STATES_CITIES) {
    const hasCity = s.cities.some((c) => {
      const lower = c.toLowerCase();
      return lower === cleanCity || lower.includes(cleanCity) || cleanCity.includes(lower);
    });
    if (hasCity) {
      return s.name;
    }
  }
  return null;
}

/**
 * Get flattened list of all cities across India
 */
export function getAllIndianCities(): string[] {
  const set = new Set<string>();
  INDIAN_STATES_CITIES.forEach((s) => s.cities.forEach((c) => set.add(c)));
  return Array.from(set).sort();
}
